async def one(i,t):
    c=edge_tts.Communicate(t,"ru-RU-DmitryNeural",rate="+10%",boundary="WordBoundary")
    words=[];audio=b""
    async for ch in c.stream():
        if ch["type"]=="audio": audio+=ch["data"]
        elif ch["type"]=="WordBoundary": words.append([ch["offset"]/1e7,(ch["offset"]+ch["duration"])/1e7,ch["text"]])
    open(f"{OUT}/s{i:02d}.mp3","wb").write(audio)
    return dict(i=i,text=t,words=words)
async def main():
    res=[await one(i,t) for i,t in enumerate(S)]
    json.dump(res,open(f"{OUT}/words.json","w"),ensure_ascii=False,indent=1)
asyncio.run(main())
